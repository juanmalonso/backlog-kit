#!/usr/bin/env node
// Genera el plugin de Claude Code (plugins/backlog-kit y plugins/backlog-kit-en) y el marketplace
// desde las mismas plantillas que usa el init. Con --check falla si lo commiteado quedó viejo.
//
//   node scripts/build-plugin.mjs [--check]
//
// El plugin trae skills, subagentes, hooks (contexto, recordatorio y los guards del proyecto si
// existen) y el servidor MCP, con su propia copia de la librería. Los scripts pm:* siguen en el
// proyecto: el init los instala y el plugin los usa.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { AGENTS, SKILLS, buildConfig, render, templateContext } from '../src/init/scaffold.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const KIT = path.join(ROOT, 'kit');
const pkg = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const check = process.argv.includes('--check');

const PLUGINS = [
  { lang: 'es', name: 'backlog-kit', description: 'Backlog de historias en .pm/: skills /hu-*, subagentes revisor-criterios y refinador, contexto automático de la historia, recordatorio de log y MCP del backlog.' },
  { lang: 'en', name: 'backlog-kit-en', description: 'Story backlog in .pm/: /story-* skills, criteria-reviewer and refiner subagents, automatic story context, log reminder and backlog MCP.' },
];

function files() {
  const out = new Map();
  const put = (rel, content) => out.set(rel, content);
  for (const p of PLUGINS) {
    const base = `plugins/${p.name}`;
    const ctx = templateContext(buildConfig({ language: p.lang, github: true, gitGuard: true }), { claude: 'plugin', mcp: true });
    const tpl = (name) => render(readFileSync(path.join(KIT, 'i18n', p.lang, name), 'utf8'), ctx);
    put(
      `${base}/.claude-plugin/plugin.json`,
      `${JSON.stringify(
        {
          name: p.name,
          displayName: p.lang === 'en' ? 'Backlog Kit' : 'Backlog Kit (es)',
          version: pkg.version,
          description: p.description,
          author: { name: 'Juan Manuel Alonso' },
          homepage: 'https://github.com/juanmalonso/backlog-kit',
          repository: 'https://github.com/juanmalonso/backlog-kit',
          license: 'MIT',
          keywords: ['backlog', 'user stories', 'kanban', 'workflow'],
        },
        null,
        2,
      )}\n`,
    );
    for (const s of SKILLS[p.lang]) put(`${base}/skills/${s}/SKILL.md`, tpl(`skills/${s}.md`));
    for (const a of AGENTS[p.lang]) put(`${base}/agents/${a}.md`, tpl(`agents/${a}.md`));
    const cmd = (script, ...args) => ({ type: 'command', command: ['node', `"\${CLAUDE_PLUGIN_ROOT}/kit/scripts/claude/${script}.mjs"`, ...args].join(' '), timeout: 20 });
    put(
      `${base}/hooks/hooks.json`,
      `${JSON.stringify(
        {
          hooks: {
            SessionStart: [{ matcher: 'startup|resume|clear|compact', hooks: [cmd('session-context')] }],
            UserPromptSubmit: [{ hooks: [cmd('prompt-context')] }],
            Stop: [{ hooks: [cmd('stop-check')] }],
            // Los guards son del proyecto (dependen de su config): el plugin los corre si existen.
            PostToolUse: [{ matcher: 'Write|Edit|MultiEdit', hooks: [cmd('project-hook', 'pm-guard')] }],
            PreToolUse: [{ matcher: 'Bash', hooks: [cmd('project-hook', 'git-guard')] }],
          },
        },
        null,
        2,
      )}\n`,
    );
    put(
      `${base}/.mcp.json`,
      `${JSON.stringify({ mcpServers: { backlog: { command: 'node', args: ['${CLAUDE_PLUGIN_ROOT}/kit/scripts/mcp/server.mjs'], env: { BACKLOG_ROOT: '${CLAUDE_PROJECT_DIR}' } } } }, null, 2)}\n`,
    );
    for (const dir of ['lib', 'claude', 'mcp'])
      for (const f of readdirSync(path.join(KIT, 'scripts', dir)))
        put(`${base}/kit/scripts/${dir}/${f}`, readFileSync(path.join(KIT, 'scripts', dir, f), 'utf8'));
    put(
      `${base}/README.md`,
      p.lang === 'en'
        ? `# ${p.name}\n\nGenerated by \`scripts/build-plugin.mjs\` from backlog-kit's templates: do not edit by hand.\n\nInstall: \`/plugin marketplace add juanmalonso/backlog-kit\` and \`/plugin install ${p.name}@backlog-kit\`. The project needs backlog-kit's \`.pm/\` and scripts (\`npx github:juanmalonso/backlog-kit init --lang en --claude plugin\`). Skills use the English preset status names; if \`.pm/config.json\` renames them, the scripts and the MCP use the configured names.\n`
        : `# ${p.name}\n\nGenerado por \`scripts/build-plugin.mjs\` desde las plantillas de backlog-kit: no se edita a mano.\n\nInstalación: \`/plugin marketplace add juanmalonso/backlog-kit\` y \`/plugin install ${p.name}@backlog-kit\`. El proyecto necesita el \`.pm/\` y los scripts de backlog-kit (\`npx github:juanmalonso/backlog-kit init --claude plugin\`). Las skills usan los nombres de estado del preset en español; si \`.pm/config.json\` los renombra, los scripts y el MCP usan los del config.\n`,
    );
  }
  put(
    '.claude-plugin/marketplace.json',
    `${JSON.stringify(
      {
        name: 'backlog-kit',
        description: 'Backlog de historias en markdown dentro del repo / Markdown story backlog in your repo',
        owner: { name: 'Juan Manuel Alonso' },
        plugins: PLUGINS.map((p) => ({ name: p.name, source: `./plugins/${p.name}`, description: p.description })),
      },
      null,
      2,
    )}\n`,
  );
  return out;
}

function walk(dir) {
  return existsSync(dir) ? readdirSync(dir).flatMap((n) => (statSync(path.join(dir, n)).isDirectory() ? walk(path.join(dir, n)) : [path.join(dir, n)])) : [];
}

const want = files();
const have = new Set([...walk(path.join(ROOT, 'plugins')), ...walk(path.join(ROOT, '.claude-plugin'))].map((f) => path.relative(ROOT, f)));
if (check) {
  const stale = [...want].filter(([rel, c]) => !existsSync(path.join(ROOT, rel)) || readFileSync(path.join(ROOT, rel), 'utf8') !== c).map(([rel]) => rel);
  const extra = [...have].filter((rel) => !want.has(rel));
  if (stale.length || extra.length) {
    console.error(`✗ plugin viejo / stale plugin: node scripts/build-plugin.mjs\n${[...stale, ...extra].map((f) => `  - ${f}`).join('\n')}`);
    process.exit(1);
  }
  console.log('✓ plugin al día');
} else {
  rmSync(path.join(ROOT, 'plugins'), { recursive: true, force: true });
  for (const [rel, content] of want) {
    mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true });
    writeFileSync(path.join(ROOT, rel), content);
  }
  console.log(`✓ plugin generado (${want.size} archivos)`);
}
